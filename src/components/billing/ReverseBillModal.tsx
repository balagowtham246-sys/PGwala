import React, { useState } from 'react';
import {
  Pressable,
  ScrollView,
  StyleSheet,
  Text,
  TextInput,
  View,
} from 'react-native';
import { AlertTriangle, RotateCcw, XCircle } from 'lucide-react-native';

import { BottomSheetModal } from '@/components/ui/bottom-sheet-modal';
import {
  DestructiveButton,
  OwnerSharedStyles,
  SecondaryButton,
} from '@/components/ui/owner';
import { OwnerTheme } from '@/constants/theme';
import { formatPaiseToRupees } from '@/lib/billing-utils';
import { triggerSelectionHaptic } from '@/lib/haptics';

export type ReverseBillModalMode = 'reverse_payment' | 'cancel_bill';

export interface ReverseBillTarget {
  mode: ReverseBillModalMode;
  chargeId: string;
  residentName: string;
  roomNumber: string;
  billLabel: string;
  amountPaise: number;
  paidPaise?: number;
}

const REVERSE_PAYMENT_REASONS = [
  'Wrong resident',
  'Duplicate entry',
  'Payment bounced',
  'Amount mistake',
];

const CANCEL_BILL_REASONS = [
  'Wrong EB amount',
  'Wrong room split',
  'Generated by mistake',
  'Resident vacated',
];

interface ReverseBillModalProps {
  visible: boolean;
  target: ReverseBillTarget | null;
  submitting: boolean;
  onClose: () => void;
  onConfirm: (target: ReverseBillTarget, reason: string) => Promise<void> | void;
}

export function ReverseBillModal({
  visible,
  target,
  submitting,
  onClose,
  onConfirm,
}: ReverseBillModalProps) {
  const [selectedChip, setSelectedChip] = useState<string>('');
  const [customReason, setCustomReason] = useState('');
  const [errorText, setErrorText] = useState<string | null>(null);

  if (!target) return null;

  const isReversePayment = target.mode === 'reverse_payment';
  const chips = isReversePayment ? REVERSE_PAYMENT_REASONS : CANCEL_BILL_REASONS;

  const handleClose = () => {
    setSelectedChip('');
    setCustomReason('');
    setErrorText(null);
    onClose();
  };

  const handleConfirmPress = () => {
    const finalReason = customReason.trim() || selectedChip.trim();
    if (!finalReason) {
      setErrorText('Select or enter a short reason.');
      return;
    }
    setErrorText(null);
    void onConfirm(target, finalReason);
  };

  return (
    <BottomSheetModal
      visible={visible}
      onClose={handleClose}
      title={isReversePayment ? 'Reverse Payment' : 'Cancel Unpaid Bill'}
      subtitle={`${target.residentName} · Room ${target.roomNumber} · ${target.billLabel}`}
      disabled={submitting}
      maxHeight="85%">
      <ScrollView
        showsVerticalScrollIndicator={false}
        keyboardShouldPersistTaps="handled"
        contentContainerStyle={styles.body}>
        <View style={styles.warningCard}>
          <AlertTriangle size={16} color="#B91C1C" style={{ marginTop: 1 }} />
          <Text style={styles.warningText}>
            {isReversePayment
              ? `Reverses ${formatPaiseToRupees(target.paidPaise ?? target.amountPaise)} recorded on this bill and reopens it as Unpaid. Audit history is preserved.`
              : `Cancels this unpaid ${formatPaiseToRupees(target.amountPaise)} bill so you can re-generate or re-allocate the corrected amount.`}
          </Text>
        </View>

        <Text style={OwnerSharedStyles.inputLabel}>Reason *</Text>
        <View style={styles.chipWrap}>
          {chips.map((reason) => {
            const active = selectedChip === reason && !customReason.trim();
            return (
              <Pressable
                key={reason}
                style={[styles.chip, active && styles.chipActive]}
                onPress={() => {
                  triggerSelectionHaptic();
                  setSelectedChip(reason);
                  setCustomReason('');
                  setErrorText(null);
                }}>
                <Text style={[styles.chipText, active && styles.chipTextActive]}>
                  {reason}
                </Text>
              </Pressable>
            );
          })}
        </View>

        <TextInput
          style={OwnerSharedStyles.textInput}
          placeholder="Or type a custom reason..."
          placeholderTextColor={OwnerTheme.colors.textMuted}
          value={customReason}
          onChangeText={(val) => {
            setCustomReason(val);
            if (val.trim()) setSelectedChip('');
            setErrorText(null);
          }}
          maxLength={120}
        />

        {errorText ? <Text style={styles.errorText}>{errorText}</Text> : null}
      </ScrollView>

      <View style={styles.footer}>
        <SecondaryButton
          label="Keep"
          disabled={submitting}
          onPress={handleClose}
          style={{ flex: 1 }}
        />
        <DestructiveButton
          label={isReversePayment ? 'Confirm Reverse' : 'Cancel Bill'}
          icon={isReversePayment ? RotateCcw : XCircle}
          loading={submitting}
          disabled={submitting}
          onPress={handleConfirmPress}
          style={{ flex: 1.6 }}
        />
      </View>
    </BottomSheetModal>
  );
}

const styles = StyleSheet.create({
  body: {
    gap: 12,
    paddingBottom: 6,
  },
  warningCard: {
    flexDirection: 'row',
    alignItems: 'flex-start',
    gap: 8,
    backgroundColor: '#FEF2F2',
    borderWidth: 1,
    borderColor: '#FECACA',
    borderRadius: 12,
    padding: 12,
  },
  warningText: {
    flex: 1,
    fontSize: 12,
    lineHeight: 17,
    fontWeight: '600',
    color: '#991B1B',
  },
  chipWrap: {
    flexDirection: 'row',
    flexWrap: 'wrap',
    gap: 8,
  },
  chip: {
    paddingHorizontal: 12,
    paddingVertical: 8,
    borderRadius: 18,
    backgroundColor: '#F8FAFC',
    borderWidth: 1,
    borderColor: '#E2E8F0',
  },
  chipActive: {
    backgroundColor: '#FEF2F2',
    borderColor: '#EF4444',
  },
  chipText: {
    fontSize: 12,
    fontWeight: '600',
    color: '#475569',
  },
  chipTextActive: {
    color: '#B91C1C',
    fontWeight: '700',
  },
  errorText: {
    fontSize: 12,
    fontWeight: '600',
    color: OwnerTheme.colors.danger,
  },
  footer: {
    flexDirection: 'row',
    gap: 10,
    marginTop: 14,
  },
});
